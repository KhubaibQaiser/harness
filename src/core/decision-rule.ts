// The generated rule for one team decision (spec §4.1, §4.2). Pure; no I/O.
import { DECISIONS_DIR, type TeamDecision } from './decision-file.js';

export const ruleRel = (id: string): string => `.claude/rules/harness-decision-${id}.md`;
export const RULE_GLOB = /^\.claude\/rules\/harness-decision-[^/]+\.md$/;

// Decision text is untrusted: one line-end form, and no `<!--` that could open a comment or fake a harness marker.
const clean = (s: string): string => s.replace(/\r\n?/g, '\n').replace(/<!--/g, '&lt;!--');

/** The rule's bytes; `lines` is the uncut count of content lines after the frontmatter. */
export function renderRule(d: TeamDecision, cap: number): { text: string; lines: number; oversized: boolean } {
  const src = `${DECISIONS_DIR}/${d.id}.md`;
  // JSON strings are valid YAML double-quoted scalars: the globs can't break out of the list.
  const front = ['---', 'paths:', ...d.paths.map((p) => `  - ${JSON.stringify(p)}`), '---'];
  const body = clean(d.body).replace(/^\n+/, '').trimEnd();
  const content = [
    `<!-- Generated by harness from ${src}. Change it with harness remember, not here. -->`,
    `# Team decision: ${clean(d.title)}`,
    '',
    ...(body === '' ? [] : [...body.split('\n'), '']),
    `Source: \`${src}\`, confirmed ${d.verified_on} at \`${d.verified_at.slice(0, 7)}\`.`,
  ];
  const lines = content.length;
  const oversized = lines > cap;
  const kept = oversized ? [...content.slice(0, cap - 1), `Cut to ${cap} lines: read ${src} for the rest.`] : content;
  return { text: [...front, ...kept].join('\n') + '\n', lines, oversized };
}
